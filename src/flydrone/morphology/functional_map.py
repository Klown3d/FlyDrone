"""Join inferred FAFB PFL3 columns to the published 12-column model angles."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

from flydrone.data.acquire import file_hash, save_json, utc_now


SOURCE = "https://doi.org/10.1038/s41586-023-07006-3"
GOAL_DEG = [-15, -45, -75, -105, -135, -165, 165, 135, 105, 75, 45, 15]
HEADING_DEG = {
    "right": [-67.5, -112.5, -157.5, -157.5, 157.5, 112.5, 112.5, 67.5, 22.5, 22.5, -22.5, -67.5],
    "left": [67.5, 22.5, -22.5, -22.5, -67.5, -112.5, -112.5, -157.5, 157.5, 157.5, 112.5, 67.5],
}


def build(root: Path) -> None:
    manifest_path = root / "data/manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    output_dir = root / manifest["extraction"]["output_dir"]
    features = pd.read_csv(output_dir / "morphology-features.csv", dtype={"root_id": str})
    pfl3 = features.loc[features["selected_type"].eq("PFL3")].copy()
    pfl3["functional_column"] = pfl3["geometric_column"]
    pfl3["preferred_goal_deg"] = pfl3["functional_column"].map(
        {f"FB{i:02d}": value for i, value in enumerate(GOAL_DEG, 1)}
    )
    pfl3["preferred_heading_deg"] = [
        HEADING_DEG[side][int(column[2:]) - 1]
        for side, column in zip(pfl3["lal_projection_side"], pfl3["functional_column"])
    ]
    pfl3["mapping_status"] = "inferred_FAFB_geometry_plus_published_12_column_model"
    pfl3["angle_source"] = SOURCE
    columns = ["root_id", "selected_type", "functional_column", "lal_projection_side",
               "preferred_goal_deg", "preferred_heading_deg", "mapping_status", "angle_source"]
    mapping_path = output_dir / "functional-mapping.csv"
    pfl3[columns].sort_values(["functional_column", "lal_projection_side"]).to_csv(mapping_path, index=False)
    report = {
        "created_at": utc_now(),
        "source": SOURCE,
        "source_model": "12 functional FB columns; angle lists reported in Methods",
        "mapping_scope": "PFL3 only",
        "mapping_status": "hypothesis generated by matching FAFB skeleton median-x rank to published column order",
        "warning": "This is not a source-provided per-root-ID functional annotation and must be tested against synapse-coordinate or expert column labels.",
        "fc2_decision": "Primary goal-input population is FC2B plus FC2C. The experimental driver anatomy was consistent with FC2B or FC2C and did not distinguish them; FC2A is retained only as a comparison.",
        "mapping": mapping_path.relative_to(root).as_posix(),
        "mapping_sha256": file_hash(mapping_path),
    }
    report_path = output_dir / "functional-mapping-report.json"
    save_json(report_path, report)
    manifest["functional_mapping"] = {
        "status": "provisional_testable_mapping",
        "mapping": mapping_path.relative_to(root).as_posix(),
        "mapping_sha256": file_hash(mapping_path),
        "report": report_path.relative_to(root).as_posix(),
        "report_sha256": file_hash(report_path),
        "primary_fc2_subtypes": ["FC2B", "FC2C"],
        "comparison_only_fc2_subtypes": ["FC2A"],
    }
    manifest["status"] = "functional_mapping_provisional_synapse_coordinates_pending"
    save_json(manifest_path, manifest)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path.cwd())
    args = parser.parse_args()
    build(args.root.resolve())
